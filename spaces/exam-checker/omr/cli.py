"""Command line interface for the OMR grading pipeline."""
from __future__ import annotations

import argparse
import glob
import sys
from pathlib import Path

from omr.grading import AnswerKey
from omr.layout import Layout
from omr.pipeline import OMRPipeline
from omr.roster import Roster


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="omr",
        description="Optical Mark Recognition (OMR) & Document Grading Pipeline",
    )
    parser.add_argument(
        "--layout",
        "-l",
        required=True,
        help="Path to resolved layout.json generated by the browser sheet builder",
    )
    parser.add_argument(
        "--key",
        "-k",
        required=True,
        help="Path to answer key JSON file",
    )
    parser.add_argument(
        "--roster",
        "-r",
        help="Path to student roster CSV file (containing Student ID and Full Name)",
    )
    parser.add_argument(
        "--scans",
        "-s",
        nargs="+",
        required=True,
        help="Paths or glob patterns to scanned exam images (JPEG, PNG)",
    )
    parser.add_argument(
        "--out",
        "-o",
        default="output",
        help="Directory to save derivative annotated scans and reports (default: output/)",
    )
    parser.add_argument(
        "--resolution",
        type=float,
        default=10.0,
        help="Canonical resolution in pixels per mm (default: 10.0 = 254 DPI)",
    )

    args = parser.parse_args(argv)

    # 1. Expand input scan file paths
    scan_files: list[Path] = []
    for pattern in args.scans:
        matches = glob.glob(pattern)
        if matches:
            scan_files.extend(Path(m) for m in matches)
        else:
            p = Path(pattern)
            if p.exists():
                scan_files.append(p)

    if not scan_files:
        print(f"Error: No image files matched: {args.scans}", file=sys.stderr)
        return 1

    # 2. Load layout and answer key
    print(f"[*] Loading layout: {args.layout}")
    layout = Layout.load(args.layout)

    print(f"[*] Loading answer key: {args.key}")
    key = AnswerKey.load(args.key)

    # 3. Load roster if provided
    roster = None
    if args.roster:
        print(f"[*] Ingesting roster: {args.roster}")
        roster = Roster.load(args.roster)
        print(f"    Roster contains {len(roster)} enrolled students.")
        for w in roster.warnings:
            print(f"    [!] Roster notice: {w}")

    # 4. Initialize pipeline
    pipeline = OMRPipeline(
        layout=layout,
        answer_key=key,
        roster=roster,
        px_per_mm=args.resolution,
    )

    # 5. Process batch
    print(f"[*] Processing {len(scan_files)} exam scan(s)...")
    try:
        res = pipeline.process_batch(scan_files, args.out)
    except Exception as exc:
        print(f"Error processing batch: {exc}", file=sys.stderr)
        return 1

    print("\n" + "=" * 60)
    print(f"BATCH GRADING COMPLETE: {len(res.grades)} exam(s) processed successfully.")
    if res.failed_scans:
        print(f"[!] {len(res.failed_scans)} scan(s) failed:")
        for fname, err in res.failed_scans:
            print(f"    - {fname}: {err}")
    print("=" * 60)
    print(f"Cohort Summary:")
    print(f"  Mean Score:     {res.psychometrics.mean_score:.2f} / {res.psychometrics.total_possible_score:.2f} ({res.psychometrics.mean_percentage:.1f}%)")
    print(f"  Median Score:   {res.psychometrics.median_score:.2f}")
    print(f"  Score Std Dev:  {res.psychometrics.std_dev:.2f}")
    print(f"  Cronbach Alpha: {res.psychometrics.cronbach_alpha:.3f}")
    print("\nGenerated Artifacts:")
    print(f"  - Item Analysis Report: {res.report_path}")
    print(f"  - Grades JSON:          {res.grades_json_path}")
    print(f"  - Annotated Scans:      {len(res.annotated_paths)} files in {res.output_dir / 'annotated'}")
    print("=" * 60)

    return 0


if __name__ == "__main__":
    sys.exit(main())
